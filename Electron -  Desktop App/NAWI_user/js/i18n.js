  const resources = { mr: { translation: {} }, hi: { translation: {} } };
  Object.entries(phrases).forEach(([key, values]) => {
    resources.mr.translation[key] = values[0];
    resources.hi.translation[key] = values[1];
  });

  let savedLanguage = 'en';
  try {
    savedLanguage = localStorage.getItem('nawi-language') || 'en';
  } catch (error) {
    savedLanguage = 'en';
  }
  const initialLanguage = ['en', 'mr', 'hi'].includes(savedLanguage) ? savedLanguage : 'en';
  const originalText = new WeakMap();
  const originalAttributes = new WeakMap();
  const translatedAttributes = ['placeholder', 'title', 'aria-label', 'alt'];
  const originalTitle = document.title;

  function translateNode(node) {
    const source = originalText.get(node) ?? node.nodeValue;
    if (!source.trim()) return;
    originalText.set(node, source);

    const leading = source.match(/^\s*/)[0];
    const trailing = source.match(/\s*$/)[0];
    const phrase = source.trim();
    let translated = window.i18next.t(phrase, { defaultValue: phrase });
    if (translated === phrase) {
      const prefixMatch = phrase.match(/^((?:\d+(?:\.\d+)*\.?\s+|[✓○—]\s+))(.+)$/);
      if (prefixMatch) {
        const translatedSuffix = window.i18next.t(prefixMatch[2], { defaultValue: prefixMatch[2] });
        if (translatedSuffix !== prefixMatch[2]) translated = `${prefixMatch[1]}${translatedSuffix}`;
      }
    }
    const translatedText = `${leading}${translated}${trailing}`;
    if (node.nodeValue !== translatedText) node.nodeValue = translatedText;
  }

  function translateElementAttributes(element) {
    let originals = originalAttributes.get(element);
    if (!originals) {
      originals = new Map();
      originalAttributes.set(element, originals);
    }

    translatedAttributes.forEach((attribute) => {
      if (!element.hasAttribute(attribute)) return;
      const source = originals.get(attribute) ?? element.getAttribute(attribute);
      originals.set(attribute, source);
      const translated = window.i18next.t(source, { defaultValue: source });
      if (element.getAttribute(attribute) !== translated) element.setAttribute(attribute, translated);
    });
  }

  function translatePage() {
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    let node;
    while ((node = walker.nextNode())) translateNode(node);

    document.querySelectorAll('*').forEach(translateElementAttributes);
    document.title = window.i18next.t(originalTitle, { defaultValue: originalTitle });
    document.documentElement.lang = window.i18next.language;

    document.querySelectorAll('.lang-icon-btn').forEach((button) => {
      const language = { English: 'en', Marathi: 'mr', Hindi: 'hi' }[button.dataset.val];
      const active = language === window.i18next.language;
      button.classList.toggle('active', active);
      button.setAttribute('aria-pressed', String(active));
    });
  }

  function changeLanguage(language) {
    window.i18next.changeLanguage(language, () => {
      try {
        localStorage.setItem('nawi-language', language);
      } catch (error) {
        // Language still applies for this page when storage is unavailable.
      }
      translatePage();
      document.dispatchEvent(new CustomEvent('nawi:languageChanged', { detail: { language } }));
    });
  }

  window.i18next.init({
    lng: initialLanguage,
    fallbackLng: 'en',
    resources,
    keySeparator: false,
    nsSeparator: false,
    interpolation: { escapeValue: false }
  }, (error) => {
    if (error) console.error('Unable to initialize translations:', error);
    translatePage();

    const observer = new MutationObserver((mutations) => {
      mutations.forEach((mutation) => {
        if (mutation.type === 'characterData') translateNode(mutation.target);
        if (mutation.type === 'attributes') translateElementAttributes(mutation.target);
        mutation.addedNodes?.forEach((addedNode) => {
          if (addedNode.nodeType === Node.TEXT_NODE) translateNode(addedNode);
          if (addedNode.nodeType === Node.ELEMENT_NODE) {
            const walker = document.createTreeWalker(addedNode, NodeFilter.SHOW_TEXT);
            let textNode;
            while ((textNode = walker.nextNode())) translateNode(textNode);
            translateElementAttributes(addedNode);
            addedNode.querySelectorAll('*').forEach(translateElementAttributes);
          }
        });
      });
    });
    observer.observe(document.body, {
      childList: true,
      characterData: true,
      subtree: true,
      attributes: true,
      attributeFilter: translatedAttributes
    });
  });

  document.addEventListener('click', (event) => {
    const button = event.target.closest('.lang-icon-btn');
    if (!button) return;

    const language = { English: 'en', Marathi: 'mr', Hindi: 'hi' }[button.dataset.val];
    if (language) changeLanguage(language);
  });
